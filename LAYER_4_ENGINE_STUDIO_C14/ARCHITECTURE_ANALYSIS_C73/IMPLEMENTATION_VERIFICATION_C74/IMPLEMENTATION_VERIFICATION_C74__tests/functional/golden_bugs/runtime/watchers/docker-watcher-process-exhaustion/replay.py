"""Replay historical Python slices and regenerate the bounded Lean witness."""

from pathlib import Path
from queue import Queue
from tempfile import TemporaryDirectory
from unittest.mock import Mock
import os
import sys

if not __package__:
    directory = Path(__file__).resolve().parent
    engine = next(
        parent
        for parent in directory.parents
        if parent.name == "LAYER_4_ENGINE_STUDIO_C14"
    )
    sys.path.insert(0, str(engine))
    __package__ = ".".join(directory.relative_to(engine).parts)

from .analyze import analyze, lean_source

HERE = Path(__file__).parent
models = []
for version in ("before", "fixed"):
    fixture = HERE / f"{version}.py.txt"
    model = analyze(fixture)
    assert model is not None
    models.append(model)
    native, polling = Mock(), Mock()
    namespace = {
        "Path": Path,
        "Queue": Queue,
        "NativeObserver": None,
        "_Handler": lambda _: object(),
        "PollingObserverVFS": Mock(return_value=polling),
        "os": os,
    }
    exec(
        "from __future__ import annotations\n" + fixture.read_text(), namespace
    )
    with TemporaryDirectory() as temp:
        root = Path(temp)
        for i in range(80):
            (root / f"dir{i}").mkdir()
        options = {
            "observer_factory": lambda: native,
            "exclude_directory": lambda _: False,
        }
        if model[0]:
            options["poll_bind_mount"] = True
        watcher = namespace["SourceWatcher"](root, root, **options)
        watcher.start()
        assert native.schedule.call_count == (0 if model[0] else 81)
        assert polling.schedule.call_count == (1 if model[0] else 0)
        assert namespace["PollingObserverVFS"].call_count == int(model[0])
        schedules = (
            polling.schedule.call_args_list
            if model[0]
            else native.schedule.call_args_list
        )
        assert schedules[0].kwargs["recursive"] == model[0]
        print(version, "polling=", model[0], "schedules=", len(schedules))

before, fixed = models
assert before == (False, True) and fixed == (True, False)
lean = "-- Generated by replay.py from the two fixture ASTs.\n"
for label, model in zip(("before", "fixed"), models):
    source = (
        lean_source(*model)
        .replace("pollingObserver", label + "Polling")
        .replace("filteredRoot", label + "Filtered")
        .replace("schedules", label + "Schedules")
        .replace("theorem observed", "theorem " + label + "Observed")
    )
    lean += "\n" + source
lean += (
    "\n"
    "theorem old_fails : beforePolling = false ∧ "
    "beforeSchedules 80 = 81 := by decide\n"
    "theorem fixed_bounded (n : Nat) : fixedPolli"
    "ng = true ∧ fixedSchedules n = 1 := by\n"
    "  simp [fixedPolling, fixedSchedules, fixedF"
    "iltered]\n"
)
(HERE / "regression.lean").write_text(lean)
